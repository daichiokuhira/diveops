import asyncio, http.server, threading, functools, os, sys
from playwright.async_api import async_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(os.path.join(ROOT, 'docs'))
srv = http.server.ThreadingHTTPServer(('127.0.0.1', 8765), functools.partial(http.server.SimpleHTTPRequestHandler, directory='.'))
threading.Thread(target=srv.serve_forever, daemon=True).start()
SH = os.path.join(ROOT, 'tests', 'shots') + '/'
os.makedirs(SH, exist_ok=True)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, locale='ja-JP', timezone_id='Asia/Tokyo')
        pg = await ctx.new_page()
        errs = []
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
        pg.on('pageerror', lambda e: errs.append(str(e) + ' @ ' + (e.stack or '')[:400]))
        await pg.goto('http://127.0.0.1:8765/index.html')
        await pg.screenshot(path=SH+'01_home.png')
        await pg.click('text=新しい事案を始める')
        await pg.fill('#n-site', '平良港 第3岸壁')
        await pg.fill('#n-title', '水中捜索訓練')
        await pg.select_option('#n-cmd', '1001')
        await pg.click('[data-act="draft-diver"][data-v="1002"]')
        await pg.click('[data-act="draft-diver"][data-v="1003"]')
        await pg.screenshot(path=SH+'02_new.png')
        await pg.click('text=記録を始める')
        await pg.screenshot(path=SH+'03_board_wait.png')
        # 潜降
        await pg.click('[data-act="sheet"][data-sheet="down"][data-i="0"]')
        await pg.click('[data-act="down-depth"][data-v="18"]')
        await pg.screenshot(path=SH+'04_down_sheet.png')
        await pg.click('[data-act="do-down"]')
        # 時刻を40分前にずらす（潜水中の表示を確かめる）
        await pg.evaluate("""() => { const s = JSON.parse(localStorage.getItem('diveops.v1')); const inc = s.incidents.find(i=>i.status==='active'); inc.divers[0].current.startAt = new Date(Date.now()-46*60000).toISOString(); localStorage.setItem('diveops.v1', JSON.stringify(s)); }""")
        await pg.reload()
        await pg.click('.item >> nth=0')
        await pg.wait_for_timeout(1200)
        await pg.screenshot(path=SH+'05_board_down.png')
        await pg.click('[data-act="sheet"][data-sheet="up"][data-i="0"]')
        await pg.fill('#u-depth', '17')
        await pg.dispatch_event('#u-depth', 'input')
        await pg.fill('#u-endp', '70')
        await pg.screenshot(path=SH+'06_up_sheet.png')
        await pg.click('[data-act="do-up"]')
        # 休息を65分経過させる
        await pg.evaluate("""() => { const s = JSON.parse(localStorage.getItem('diveops.v1')); const inc = s.incidents.find(i=>i.status==='active'); const d = inc.divers[0].dives[0]; d.startAt = new Date(Date.now()-(65+46)*60000).toISOString(); d.endAt = new Date(Date.now()-65*60000).toISOString(); localStorage.setItem('diveops.v1', JSON.stringify(s)); }""")
        await pg.reload()
        await pg.click('.item >> nth=0')
        await pg.wait_for_timeout(1200)
        await pg.screenshot(path=SH+'07_board_rest.png')
        await pg.click('[data-act="sheet"][data-sheet="diver"][data-i="0"]')
        await pg.screenshot(path=SH+'08_diver_detail.png', full_page=False)
        await pg.click('[data-act="sheet-close"]')
        await pg.click('[data-act="go-summary"]')
        await pg.screenshot(path=SH+'09_summary.png', full_page=True)
        csv = await pg.evaluate("""() => { const s = JSON.parse(localStorage.getItem('diveops.v1')); return s.incidents.length; }""")
        await pg.click('[data-act="close-inc"]')
        await pg.goto('http://127.0.0.1:8765/index.html')
        await pg.wait_for_timeout(800)
        await pg.screenshot(path=SH+'09b_after.png')
        print('ERRS so far', errs)
        await pg.click('[data-act="go"][data-to="tables"]')
        await pg.screenshot(path=SH+'10_tables.png', full_page=True)
        await pg.click('[data-act="back"]')
        await pg.click('[data-act="go"][data-to="calc"]')
        await pg.screenshot(path=SH+'11_calc.png', full_page=True)
        # 暗い表示
        await ctx.close()
        ctx2 = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, color_scheme='dark', locale='ja-JP', timezone_id='Asia/Tokyo')
        pg2 = await ctx2.new_page()
        pg2.on('pageerror', lambda e: errs.append(str(e)))
        await pg2.goto('http://127.0.0.1:8765/index.html')
        await pg2.screenshot(path=SH+'12_home_dark.png')
        # 横はみ出しチェック
        ov = await pg2.evaluate("document.documentElement.scrollWidth > window.innerWidth")
        print('overflow', ov)
        print('errors', errs)
        await b.close()
asyncio.run(main())
srv.shutdown()
